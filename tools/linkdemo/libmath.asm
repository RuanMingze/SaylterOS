; ============================================================
; libmath.asm - 动态链接测试库
; ------------------------------------------------------------
; 加载地址 0x06000000，导出 slyz_add(a, b)。
; 使用 Microsoft x64 调用约定：a = rcx，b = rdx，返回值 rax。
; ============================================================
BITS 64
default abs

org 0x06000000

slyz_add:
    lea rax, [rcx + rdx]
    ret
