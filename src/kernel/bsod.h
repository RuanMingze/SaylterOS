/* ============================================================
 * bsod.h - 内核崩溃蓝屏
 * ------------------------------------------------------------
 * 蓝屏不是装饰：进入后关闭中断、屏蔽 8259、停止所有任务、
 * 不再执行任何磁盘写入，CPU 冻结在 hlt 循环里，直到用户
 * 按电源键或复位。这样能保证崩溃后的硬件状态不被进一步破坏。
 * ============================================================ */

#ifndef BSOD_H
#define BSOD_H

#include <stdint.h>

/* 进入崩溃蓝屏，不返回。
 * stop_code 会以 STOP: 0x........ 的形式显示；
 * reason 是一行可读的终止原因。 */
void bsod(uint32_t stop_code, const char *reason);

#endif /* BSOD_H */
